#!/usr/bin/env python3
"""Embed the licensed terminal symbol font for desktop and browser hosts."""
import base64
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "graphical/assets/fonts/ExosuitTerminalSymbols.ttf"
TARGET = ROOT / "graphical/src/ui/TerminalSymbolFont.hx"


def subset_font(source):
    # fontTools is needed only when updating the upstream font, not for normal builds.
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.pens.recordingPen import DecomposingRecordingPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.recalc_timestamp = False
    selected = subset.Subsetter(options=options)
    selected.populate(unicodes=[32, *range(0x2800, 0x2900)])
    selected.subset(font)
    glyphs = font.getGlyphSet()
    replacements = {}
    # Use the browser's 0.6em terminal cell, rather than Noto's varying symbol advances.
    for name in font.getGlyphOrder():
        recording = DecomposingRecordingPen(glyphs)
        glyphs[name].draw(recording)
        advance, _ = font['hmtx'].metrics[name]
        scale = 600 / advance if advance else 1
        pen = TTGlyphPen(None)
        recording.replay(TransformPen(pen, (scale, 0, 0, 1, 0, 0)))
        replacements[name] = pen.glyph()
    for name, glyph in replacements.items():
        font['glyf'][name] = glyph
        glyph.recalcBounds(font['glyf'])
        font['hmtx'].metrics[name] = (600, getattr(glyph, 'xMin', 0))
    font['hhea'].ascent = font['OS/2'].sTypoAscender = 1025
    font['hhea'].descent = font['OS/2'].sTypoDescender = -275
    font['OS/2'].usWinAscent, font['OS/2'].usWinDescent = 1025, 275
    font['OS/2'].xAvgCharWidth = 600
    font['post'].isFixedPitch = 1
    for name in font['name'].names:
        if name.nameID in [1, 3, 4, 6]:
            title = 'ExosuitTerminalSymbols' if name.nameID == 6 else 'Exosuit Terminal Symbols'
            name.string = title.encode(name.getEncoding())
    # The font travels inside the executable/wasm guest, so carry its license too.
    font['name'].setName((FONT.parent / 'OFL.txt').read_text(), 13, 3, 1, 0x409)
    font.save(FONT)


def generate():
    encoded = base64.b64encode(FONT.read_bytes()).decode("ascii")
    chunks = ",\n".join('\t\t\t"' + encoded[index:index + 120] + '"'
                         for index in range(0, len(encoded), 120))
    return '''package ui;

import haxe.crypto.Base64;
import haxe.io.Bytes;
import haxeon.ui.FontCollection;
import haxeon.ui.FontFamily;

// Generated by scripts/generate-terminal-symbol-font.py; license: graphical/assets/fonts/OFL.txt.
// Embedded so terminal art works without system fonts or extra browser asset requests.
class TerminalSymbolFont {
\tstatic var decoded:Null<Bytes> = null;

\t/** Install once per collection, after its primary monospace face. */
\tpublic static function addTo(fonts:FontCollection):Void {
\t\tvar bytes = decoded;
\t\tif (bytes == null) {
\t\t\tbytes = Base64.decode([
''' + chunks + '''
\t\t\t].join(""));
\t\t\tdecoded = bytes;
\t\t}
\t\tfonts.addData("ExosuitTerminalSymbols.ttf", bytes, FontFamily.Monospace);
\t}
}
'''


if __name__ == "__main__":
    if "--source" in sys.argv:
        subset_font(sys.argv[sys.argv.index("--source") + 1])
    source = generate()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != source:
            raise SystemExit("Regenerate TerminalSymbolFont.hx with this script")
    else:
        TARGET.write_text(source)
